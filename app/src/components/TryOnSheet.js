// "See it on me": pick a full-body photo, Gemini's image model dresses you in the Studio outfit.
// Your photo goes to the Tillie server only for this request and isn't stored.
import { useState } from "react";
import { ActivityIndicator, Image, ScrollView, StyleSheet, Text, View } from "react-native";
import * as ImagePicker from "expo-image-picker";
import { Button, RetroWindow, Sheet } from "./ui";
import { tryOnOutfit } from "../api";
import { colors, fonts, slotLabel, slotOf } from "../theme";

// remembered for this session so you don't re-pick your photo every time
let lastPhoto = null;

export default function TryOnSheet({ visible, onClose, outfit, layerOrder }) {
  const [photo, setPhoto] = useState(lastPhoto);
  const [status, setStatus] = useState("idle"); // idle | loading | done | error
  const [result, setResult] = useState(null);
  const [error, setError] = useState("");

  // outermost layer first, so Gemini knows what goes on top
  const order = layerOrder || Object.keys(outfit || {});
  const pieces = order
    .map((slot) => outfit?.[slot])
    .filter(Boolean)
    .map((p) => ({ ...p, layer: slotLabel(slotOf(p)) }));

  const pick = async (camera) => {
    if (camera) {
      const perm = await ImagePicker.requestCameraPermissionsAsync();
      if (!perm.granted) return;
    }
    const opts = { mediaTypes: ["images"], base64: true, quality: 0.5 };
    const r = camera ? await ImagePicker.launchCameraAsync(opts) : await ImagePicker.launchImageLibraryAsync(opts);
    if (r.canceled || !r.assets?.length) return;
    const a = r.assets[0];
    lastPhoto = { uri: a.uri, base64: a.base64, mimeType: a.mimeType || "image/jpeg" };
    setPhoto(lastPhoto);
    setStatus("idle");
    setResult(null);
  };

  const run = async () => {
    if (!photo || !pieces.length) return;
    setStatus("loading");
    setError("");
    try {
      const out = await tryOnOutfit(photo.base64, photo.mimeType, pieces);
      setResult(out.uri);
      setStatus("done");
    } catch (e) {
      setError(e.message);
      setStatus("error");
    }
  };

  return (
    <Sheet visible={visible} onClose={onClose} title="See it on me ✦" height="90%">
      <ScrollView contentContainerStyle={st.body}>
        <RetroWindow title={status === "done" ? "you_in_this_fit.png" : "try_on.exe"} bar="pink">
          <View style={st.stage}>
            {status === "done" && result ? (
              <Image source={{ uri: result }} style={st.img} resizeMode="contain" accessibilityLabel="You wearing this outfit, generated by Gemini" />
            ) : photo ? (
              <Image source={{ uri: photo.uri }} style={[st.img, status === "loading" && { opacity: 0.45 }]} resizeMode="contain" accessibilityLabel="Your photo" />
            ) : (
              <View style={st.empty}>
                <Text style={st.emptyBig}>Add a full-body photo</Text>
                <Text style={st.muted}>Stand straight, good light, plain background works best.</Text>
              </View>
            )}
            {status === "loading" && (
              <View style={st.overlay}>
                <ActivityIndicator size="large" color={colors.pink} />
                <Text style={st.loading}>Gemini is dressing you…</Text>
                <Text style={st.muted}>about 10–30 seconds</Text>
              </View>
            )}
          </View>
        </RetroWindow>

        {status === "done" && (
          <Text style={st.note}>AI preview by Gemini. Colors and fit are approximate, so check the size guide before you buy.</Text>
        )}
        {status === "error" && <Text style={st.error}>{error}</Text>}

        <Text style={st.section}>Wearing</Text>
        {pieces.length ? (
          <View style={st.chips}>
            {pieces.map((p) => (
              <View key={p.uid} style={st.chip}>
                <View style={[st.dot, { backgroundColor: p.color }]} />
                <Text style={st.chipText} numberOfLines={1}>{p.name}</Text>
              </View>
            ))}
          </View>
        ) : (
          <Text style={st.muted}>Put some pieces on your avatar first.</Text>
        )}

        <Button
          title={status === "done" ? "Try again" : "See it on me"}
          icon="sparkle"
          disabled={!photo || !pieces.length || status === "loading"}
          onPress={run}
        />
        <View style={{ flexDirection: "row", gap: 10 }}>
          <Button title="Choose photo" variant="outline" onPress={() => pick(false)} style={{ flex: 1 }} disabled={status === "loading"} />
          <Button title="Take photo" variant="outline" onPress={() => pick(true)} style={{ flex: 1 }} disabled={status === "loading"} />
        </View>
        <Text style={st.privacy}>Your photo is only sent to make this preview. Tillie doesn't save it.</Text>
      </ScrollView>
    </Sheet>
  );
}

const st = StyleSheet.create({
  body: { padding: 18, gap: 12, paddingBottom: 40 },
  stage: { height: 380, backgroundColor: colors.soft, alignItems: "center", justifyContent: "center" },
  img: { width: "100%", height: "100%" },
  empty: { alignItems: "center", gap: 6, padding: 24 },
  emptyBig: { fontFamily: fonts.pixel, fontSize: 24, color: colors.ink },
  overlay: { ...StyleSheet.absoluteFillObject, alignItems: "center", justifyContent: "center", gap: 6 },
  loading: { fontFamily: fonts.pixel, fontSize: 22, color: colors.pink },
  muted: { fontFamily: fonts.regular, fontSize: 13, color: colors.muted, textAlign: "center" },
  note: { fontFamily: fonts.medium, fontSize: 12, color: colors.muted, textAlign: "center" },
  error: { fontFamily: fonts.medium, fontSize: 13, color: "#C0392B", textAlign: "center" },
  section: { fontFamily: fonts.pixel, fontSize: 20, color: colors.pink },
  chips: { flexDirection: "row", flexWrap: "wrap", gap: 8 },
  chip: { flexDirection: "row", alignItems: "center", gap: 6, borderWidth: 1, borderColor: colors.chipLine, borderRadius: 16, paddingHorizontal: 10, paddingVertical: 6, maxWidth: "100%" },
  dot: { width: 12, height: 12, borderRadius: 6, borderWidth: 1, borderColor: "rgba(0,0,0,0.12)" },
  chipText: { fontFamily: fonts.medium, fontSize: 12, color: colors.ink2, flexShrink: 1 },
  privacy: { fontFamily: fonts.regular, fontSize: 11, color: colors.muted, textAlign: "center" },
});
